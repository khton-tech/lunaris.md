import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { JSDOM } from 'jsdom';
import { IDBFactory } from 'fake-indexeddb';
import { useBrowser } from '../test/browser.mjs';
import { definePlugin } from '@lunaris/sdk';
import { HostSession, composeApplication } from '@lunaris/application-host';
import { createWebviewScheduler } from '@lunaris/application-host/scheduler';
import { createBrowserStorage } from '@lunaris/browser-storage';
import { createTauriCredentials } from '@lunaris/tauri-credentials';
import { AccountSession, AccountVaults } from '@lunaris/remote';
import { Vault, VaultLocations, VaultHistory } from '@lunaris/vault';
import { FilesystemSources, Filesystem } from '@lunaris/filesystem';
import { createDevToolsLogger } from '@lunaris/dev-tools-logger';
const until = async check => { for (let i=0;i<400;i++) { if(await check())return; await new Promise(r=>setTimeout(r,20)); } assert.fail('Restore timed out'); };
test('desktop restart restores authentication and last remote Vault before selector startup', async t => {
  const serverRoot=process.env.LUNARIS_SERVER_DIRECTORY ?? path.resolve('../lunaris-server');
  const {startApplication}=await import(pathToFileURL(path.join(serverRoot,'src/application.mjs')).href);
  const {validateConfig}=await import(pathToFileURL(path.join(serverRoot,'src/config.mjs')).href);
  const base=fs.mkdtempSync(path.join(os.tmpdir(),'lunaris-session-restore-'));
  const server=await startApplication(validateConfig({port:0},base),{writeLog:()=>{}});
  const address='http://127.0.0.1:'+server.address.port;
  const nativeFetch=globalThis.fetch;
  globalThis.fetch=(url,init)=>{const {signal,...rest}=init;return nativeFetch(url,rest);};
  const dom=useBrowser(new JSDOM('<div id="app"></div>',{url:address,pretendToBeVisual:true}));
  Object.defineProperty(globalThis,'indexedDB',{configurable:true,value:new IDBFactory()});
  Object.defineProperty(globalThis,'Window',{configurable:true,value:dom.window.Window});
  Object.defineProperty(globalThis,'MutationObserver',{configurable:true,value:dom.window.MutationObserver});
  let stored=null, api, session;
  const credentialPlugin=createTauriCredentials(async(operation,value)=>{
    if(operation==='save')stored=structuredClone(value);
    if(operation==='remove' && stored?.token===value)stored=null;
    return {ok:true,value:operation==='load'?stored:null};
  });
  const tokens={account:AccountSession,catalog:AccountVaults,vault:Vault,locations:VaultLocations,history:VaultHistory,sources:FilesystemSources,fs:Filesystem};
  const bridge=definePlugin({manifest:{manifestVersion:1,id:'test.restore',version:'0.1.0',engine:'^0.1.0',sdk:'^0.1.0',entry:'./index.js',provides:[],requires:Object.values(tokens).map(v=>({kind:v.kind,id:v.id,range:'^'+v.version})),permissions:['account.access','vault.access','filesystem.access'],optionalPermissions:[]},activate(ctx){api=Object.fromEntries(Object.entries(tokens).map(([k,v])=>[k,ctx.use(v)]));api.owner=ctx.signal;}});
  const start=async()=>{
    session=new HostSession({scheduler:createWebviewScheduler(),async load(){
      const definition=composeApplication(dom.window.document.getElementById('app'),{art:'Lunaris',mode:'desktop',features:['files'],platformPlugins:[credentialPlugin],extensions:{plugins:[bridge],entrypoints:[bridge.manifest.id],grants:{[bridge.manifest.id]:bridge.manifest.permissions,[credentialPlugin.manifest.id]:credentialPlugin.manifest.permissions}}});
      const device=createBrowserStorage({config:true});
      return {...definition,grants:{...definition.grants,[device.manifest.id]:device.manifest.permissions},plugins:definition.plugins.map(p=>p.manifest.id===device.manifest.id?device:p.manifest.id==='lunaris.dev-tools-logger'?createDevToolsLogger({output:Object.fromEntries(['debug','info','warn','error'].map(k=>[k,()=>{}]))}):p)};
    }});
    await session.start();assert.equal(session.snapshot().phase,'running',JSON.stringify(session.snapshot().incidents));
  };
  t.after(async()=>{await session?.stop();await server.close();dom.window.close();globalThis.fetch=nativeFetch;fs.rmSync(base,{recursive:true,force:true});});
  await start();assert.equal((await api.account.connect(address,api.owner)).ok,true);
  assert.equal((await api.account.register('alice','correct horse battery staple')).ok,true);
  assert.equal((await api.account.login('alice','correct horse battery staple')).ok,true);
  const created=await api.catalog.create('Persistent notes');assert.equal(created.ok,true);
  const location=api.sources.location('remote',created.value.location);assert.equal(location.ok,true);
  assert.equal((await api.locations.open(location.value,{name:'Persistent notes'})).ok,true);
  const root=api.vault.current();assert.equal((await api.fs.writeText({vaultId:root.id,path:'note.md'},'Unchanged note',{mode:'create'})).ok,true);
  await until(async()=> (await api.history.list()).value?.length===1);
  assert.ok(stored?.token);await session.stop();
  await start();
  assert.equal(api.account.current().account.login,'alice');
  assert.ok(api.vault.current(),'last Vault restored automatically');
  assert.equal(api.vault.current().name,'Persistent notes');
  assert.equal((await api.history.list()).value.length,1);
  assert.equal((await api.fs.readText({vaultId:api.vault.current().id,path:'note.md'})).value.text,'Unchanged note');
  assert.equal((await api.vault.close()).ok,true);assert.equal((await api.account.logout()).ok,true);assert.equal(stored,null);
  await session.stop();await start();assert.equal(api.account.current(),null);assert.equal(api.vault.current(),null);
});
